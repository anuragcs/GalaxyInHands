import type { BlackHoleRecord } from './types';

function ra(h: number, m: number, s: number): number {
  return h + m / 60 + s / 3600;
}

function dec(d: number, m: number, s: number): number {
  const sign = d < 0 || Object.is(d, -0) ? -1 : 1;
  return sign * (Math.abs(d) + m / 60 + s / 3600);
}

